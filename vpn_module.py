PROXY_LIST = "proxy_list.txt"
STATE_FILE = ".vpn_state"
ENV_FILE = os.path.expanduser("~/.nightworld_vpn_env")
TOR_PORT = 9050

def clear(): 
    os.system('clear')
    sys.stdout.write('\033[3J')
    sys.stdout.flush()

def save_env_to_file(proxy_url):
    with open(ENV_FILE, "w") as f:
        f.write(f"export http_proxy=\"{proxy_url}\"\n")
        f.write(f"export https_proxy=\"{proxy_url}\"\n")
        f.write(f"export ALL_PROXY=\"{proxy_url}\"\n")
        f.write(f"export HTTP_PROXY=\"{proxy_url}\"\n")
        f.write(f"export HTTPS_PROXY=\"{proxy_url}\"\n")

def clear_env_file():
    if os.path.exists(ENV_FILE):
        os.remove(ENV_FILE)

def get_status():
    vpn = "OFF"; proxy = "OFF"
    
    if os.path.exists(STATE_FILE):
        with open(STATE_FILE) as f:
            state = f.read().strip()
            if state == "TOR" or state.startswith("PROXY:"): proxy = "ON"

    try:
        subprocess.check_output(["pgrep", "-x", "tor"], stderr=subprocess.DEVNULL)
        vpn = "ON"
    except subprocess.CalledProcessError: 
        vpn = "OFF"
        
    print(f"  {C}[*] VPN Tor : {W}{vpn}{N}")
    print(f"  {C}[*] Proxy   : {W}{proxy}{N}")

