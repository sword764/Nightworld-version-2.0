import os
import sys
import subprocess
import time
import random
import shutil

# ANSI Colors
C = '\033[0;36m'; G = '\033[0;32m'; Y = '\033[1;33m'; R = '\033[0;31m'; W = '\033[1;37m'; N = '\033[0m'
PROXY_LIST = "proxy_list.txt"
STATE_FILE = ".vpn_state"
TOR_PORT = 9050

def clear(): 
    os.system('clear')
    # Clear scrollback buffer
    sys.stdout.write('\033[3J')
    sys.stdout.flush()

def get_status():
    vpn = "OFF"; proxy = "OFF"
    
    # Cek state file buat Proxy (karena env hilang tiap sub-process)
    if os.path.exists(STATE_FILE):
        with open(STATE_FILE) as f:
            state = f.read().strip()
            if state == "TOR" or state == "PROXY": proxy = "ON"

    try:
        subprocess.check_output(["pgrep", "-x", "tor"], stderr=subprocess.DEVNULL)
        vpn = "ON"
    except subprocess.CalledProcessError: 
        vpn = "OFF"
        
    print(f"  {C}[*] VPN Tor : {W}{vpn}{N}")
    print(f"  {C}[*] Proxy   : {W}{proxy}{N}")

def install_tor():
    print(f"{Y}[*] Tor tidak ditemukan. Menginstall otomatis...{N}")
    is_termux = "com.termux" in os.environ.get("PREFIX", "")
    try:
        if is_termux:
            subprocess.run(["pkg", "update", "-y"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            subprocess.run(["pkg", "install", "-y", "tor"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            subprocess.run(["sudo", "apt-get", "update", "-y"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            subprocess.run(["sudo", "apt-get", "install", "-y", "tor"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        
        subprocess.check_output(["which", "tor"])
        print(f"{G}[+] Tor berhasil diinstall.{N}")
        return True
    except Exception:
        print(f"{R}[!] Gagal menginstall Tor. Coba manual.{N}")
        return False

def start_tor():
    if subprocess.run(["which", "tor"], stdout=subprocess.DEVNULL).returncode != 0:
        if not install_tor(): return

    if subprocess.run(["pgrep", "-x", "tor"], stdout=subprocess.DEVNULL).returncode == 0:
        print(f"{G}[+] Tor daemon sudah berjalan.{N}")
    else:
        print(f"{Y}[*] Menjalankan Tor daemon di background...{N}")
        subprocess.Popen(["tor"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        print("  Menunggu koneksi", end="", flush=True)
        for _ in range(5):
            time.sleep(1)
            print(".", end="", flush=True)
        print()

    proxy_url = f"socks5h://127.0.0.1:{TOR_PORT}"
    with open(STATE_FILE, "w") as f: f.write("TOR\n") # Simpan state
    
    os.environ.update({
        "http_proxy": proxy_url, "https_proxy": proxy_url,
        "ALL_PROXY": proxy_url, "HTTP_PROXY": proxy_url, "HTTPS_PROXY": proxy_url
    })
    print(f"{G}[+] VPN Tor Aktif (Port {TOR_PORT}).{N}")

def start_proxy():
    if not os.path.exists(PROXY_LIST):
        print(f"{Y}[*] {PROXY_LIST} belum ada. Mengunduh otomatis dari TheSpeedX...{N}")
        try:
            import requests
        except ImportError:
            print(f"{Y}[*] requests belum ada, menginstall...{N}")
            subprocess.run([sys.executable, "-m", "pip", "install", "-q", "requests"])
            import requests

        urls = [
            "https://raw.githubusercontent.com/TheSpeedX/PROXY-List/master/socks5.txt",
            "https://raw.githubusercontent.com/TheSpeedX/PROXY-List/master/http.txt"
        ]
        with open(PROXY_LIST, "w") as f:
            f.write("# Auto-generated by NightWorld VPN Module\n")
            for u in urls:
                try:
                    r = requests.get(u, timeout=10)
                    if r.status_code == 200: f.write(r.text + "\n")
                except Exception: pass
        print(f"{G}[+] Proxy list berhasil diunduh.{N}")

    with open(PROXY_LIST) as f:
        proxies = [line.strip() for line in f if line.strip() and not line.startswith("#")]
    
    if not proxies: print(f"{R}[!] Proxy list kosong.{N}"); return

    print(f"{C}[*] Total {len(proxies)} proxy tersedia.{N}")
    inp = input(f"  {Y}Pilih nomor proxy (atau Enter untuk Random) > {N}").strip()
    
    if not inp: chosen = random.choice(proxies)
    elif inp.isdigit() and int(inp) <= len(proxies): chosen = proxies[int(inp)-1]
    else: chosen = inp

    if not chosen.startswith(("http://", "https://", "socks5://", "socks5h://")):
        chosen = "http://" + chosen

    with open(STATE_FILE, "w") as f: f.write(f"PROXY:{chosen}\n") # Simpan state
    os.environ.update({
        "http_proxy": chosen, "https_proxy": chosen,
        "ALL_PROXY": chosen, "HTTP_PROXY": chosen, "HTTPS_PROXY": chosen
    })
    print(f"{G}[+] Proxy Aktif: {chosen}{N}")

def stop_vpn():
    subprocess.run(["pkill", "-x", "tor"], stderr=subprocess.DEVNULL)
    if os.path.exists(STATE_FILE) and open(STATE_FILE).read().startswith("TOR"):
        os.remove(STATE_FILE)
    stop_proxy(keep_state=True) # Bersihin env tapi jangan hapus file state proxy
    print(f"{G}[+] VPN Tor dimatikan & environment dibersihkan.{N}")

def stop_proxy(keep_state=False):
    for k in ["http_proxy", "https_proxy", "ALL_PROXY", "HTTP_PROXY", "HTTPS_PROXY"]:
        os.environ.pop(k, None)
    if not keep_state and os.path.exists(STATE_FILE):
        os.remove(STATE_FILE)
    print(f"{G}[+] Proxy dimatikan.{N}")

def draw_layout():
    size = shutil.get_terminal_size()
    cols = size.columns if size.columns > 0 else 80
    if cols > 100: cols = 100 
    
    border = "=" * cols
    line_dash = "-" * cols

    clear()
    print(f"{C}{border}{N}")
    print(f"{W}{'V P N  /  P R O X Y'.center(cols)}{N}")
    print(f"{C}{border}{N}")
    
    get_status()
    
    print(f"{C}{line_dash}{N}")
    print(f"  {G}[1]{N} {W}Aktifkan (Tor){N}")
    print(f"  {G}[2]{N} {W}Aktifkan (Proxy Manual){N}")
    print(f"  {R}[3]{N} {W}Matikan VPN{N}")
    print(f"  {R}[4]{N} {W}Matikan Proxy{N}")
    print(f"  {Y}[0]{N} {W}Kembali{N}")
    print(f"{C}{line_dash}{N}")
    print("\n" * 3)

def main():
    while True:
        draw_layout()
        choice = input(f"  {Y}Select menu > {N}").strip()
        
        if choice == "1": start_tor()
        elif choice == "2": start_proxy()
        elif choice == "3": stop_vpn()
        elif choice == "4": stop_proxy()
        elif choice == "0": break
        else: print(f"  {R}[!] Invalid choice.{N}"); time.sleep(1)
        
        input("\n  Press Enter to continue...")

if __name__ == "__main__":
    main()
